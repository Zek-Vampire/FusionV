-- =====================================================================
-- FusionV database schema (PostgreSQL 16)
-- Run this ONCE on an empty database named "fusionv":
--     psql -U postgres -d fusionv -f database/schema.sql
-- Then start the backend with  DDL_AUTO=validate  so Hibernate only CHECKS the tables.
-- (If you prefer, skip this file and start with DDL_AUTO=update: Hibernate creates the tables itself.
--  Use ONE of the two approaches, not both.)
-- =====================================================================

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name           VARCHAR(100)  NOT NULL,
    email               VARCHAR(150)  NOT NULL UNIQUE,
    password_hash       VARCHAR(100)  NOT NULL,
    role                VARCHAR(20)   NOT NULL CHECK (role IN ('STUDENT', 'ADMIN')),
    year_branch         VARCHAR(100),
    college             VARCHAR(150),
    motto               VARCHAR(200),
    about               VARCHAR(2000),
    location            VARCHAR(100),
    link_url            VARCHAR(300),
    resume_file_name    VARCHAR(255),
    resume_stored_name  VARCHAR(100),
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_users_email_lower ON users (LOWER(email));

CREATE TABLE skills (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(50) NOT NULL UNIQUE
);
CREATE UNIQUE INDEX uk_skills_name_lower ON skills (LOWER(name));

CREATE TABLE user_skills (
    user_id   BIGINT NOT NULL REFERENCES users (id)  ON DELETE CASCADE,
    skill_id  BIGINT NOT NULL REFERENCES skills (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, skill_id)
);

CREATE TABLE user_interests (
    user_id   BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    interest  VARCHAR(50) NOT NULL,
    PRIMARY KEY (user_id, interest)
);

CREATE TABLE hackathons (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(200) NOT NULL,
    domain                 VARCHAR(100),
    organizer              VARCHAR(150),
    location               VARCHAR(150),
    mode                   VARCHAR(20)  NOT NULL CHECK (mode IN ('ONLINE', 'OFFLINE', 'HYBRID')),
    description            VARCHAR(2000),
    eligibility            VARCHAR(500),
    start_date             DATE,
    end_date               DATE,
    registration_deadline  DATE,
    min_team_size          INTEGER CHECK (min_team_size >= 1),
    max_team_size          INTEGER CHECK (max_team_size >= 1),
    registration_url       VARCHAR(500),
    created_at             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
    CHECK (min_team_size IS NULL OR max_team_size IS NULL OR min_team_size <= max_team_size)
);
CREATE INDEX idx_hackathons_deadline ON hackathons (registration_deadline);
CREATE INDEX idx_hackathons_domain   ON hackathons (domain);

CREATE TABLE teams (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    description   VARCHAR(1000),
    hackathon_id  BIGINT REFERENCES hackathons (id),
    leader_id     BIGINT        NOT NULL REFERENCES users (id),
    max_members   INTEGER       NOT NULL CHECK (max_members BETWEEN 2 AND 10),
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_teams_hackathon ON teams (hackathon_id);
CREATE INDEX idx_teams_leader    ON teams (leader_id);

CREATE TABLE team_skills (
    team_id   BIGINT NOT NULL REFERENCES teams (id)  ON DELETE CASCADE,
    skill_id  BIGINT NOT NULL REFERENCES skills (id) ON DELETE CASCADE,
    PRIMARY KEY (team_id, skill_id)
);

CREATE TABLE team_members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id    BIGINT      NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    role       VARCHAR(20) NOT NULL CHECK (role IN ('LEADER', 'MEMBER')),
    joined_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_team_members_team_user UNIQUE (team_id, user_id)
);
CREATE INDEX idx_team_members_user ON team_members (user_id);

CREATE TABLE join_requests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id     BIGINT      NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    type        VARCHAR(20) NOT NULL CHECK (type IN ('REQUEST', 'INVITE')),
    status      VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at  TIMESTAMP
);
CREATE INDEX idx_join_requests_team ON join_requests (team_id);
CREATE INDEX idx_join_requests_user ON join_requests (user_id);
-- at most ONE pending request/invitation per (team, user): protects against double clicks
CREATE UNIQUE INDEX uk_join_requests_one_pending ON join_requests (team_id, user_id) WHERE status = 'PENDING';

CREATE TABLE posts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id        BIGINT        NOT NULL REFERENCES users (id),
    content          VARCHAR(2000) NOT NULL,
    type             VARCHAR(20)   NOT NULL CHECK (type IN ('UPDATE', 'PROJECT', 'ACHIEVEMENT')),
    title            VARCHAR(150),
    repo_url         VARCHAR(300),
    project_url      VARCHAR(300),
    organization     VARCHAR(150),
    achievement_url  VARCHAR(300),
    event_date       DATE,
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP
);
CREATE INDEX idx_posts_author  ON posts (author_id);
CREATE INDEX idx_posts_created ON posts (created_at);

-- Technologies of a project: one row per technology, not a comma separated string in the post text.
CREATE TABLE post_technologies (
    post_id     BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    technology  VARCHAR(50) NOT NULL,
    PRIMARY KEY (post_id, technology)
);

CREATE TABLE post_likes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT    NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    user_id     BIGINT    NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_post_likes_post_user UNIQUE (post_id, user_id)
);

CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT        NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    author_id   BIGINT        NOT NULL REFERENCES users (id),
    content     VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_comments_post ON comments (post_id);

CREATE TABLE resources (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploader_id         BIGINT       NOT NULL REFERENCES users (id),
    title               VARCHAR(150) NOT NULL,
    description         VARCHAR(1000),
    subject             VARCHAR(100),
    category            VARCHAR(30)  NOT NULL CHECK (category IN ('NOTES', 'QUESTION_PAPER', 'PDF', 'OTHER')),
    tags                VARCHAR(200),
    original_file_name  VARCHAR(255) NOT NULL,
    stored_file_name    VARCHAR(100) NOT NULL UNIQUE,
    content_type        VARCHAR(100) NOT NULL,
    size_bytes          BIGINT       NOT NULL CHECK (size_bytes >= 0),
    download_count      INTEGER      NOT NULL DEFAULT 0,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_resources_uploader ON resources (uploader_id);
CREATE INDEX idx_resources_category ON resources (category);
CREATE INDEX idx_resources_subject  ON resources (subject);

CREATE TABLE messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id     BIGINT        NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    sender_id   BIGINT        NOT NULL REFERENCES users (id),
    content     VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_messages_team_created ON messages (team_id, created_at);

CREATE TABLE notifications (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type             VARCHAR(30)  NOT NULL
        CHECK (type IN ('JOIN_REQUEST', 'REQUEST_ACCEPTED', 'REQUEST_REJECTED', 'TEAM_INVITE', 'NEW_MESSAGE')),
    message          VARCHAR(300) NOT NULL,
    related_team_id  BIGINT,       -- plain number, no foreign key: the notification may outlive the team
    is_read          BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_notifications_user ON notifications (user_id, is_read);
